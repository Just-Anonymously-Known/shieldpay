'use strict';
const $ = (id) => document.getElementById(id);
const id = location.pathname.split('/').pop();
let uri = '', timerId = 0, issuing = false;
const DAY = 86400000;
const dateOf = (epoch) => new Date(epoch * DAY).toISOString().slice(0, 10);

function show(which) { for (const k of ['loading', 'content', 'vouchers', 'done']) $(k).classList.toggle('hidden', k !== which); }
function finish(icon, text) { clearInterval(timerId); show('done'); $('doneIcon').textContent = icon; $('doneText').textContent = text; }

async function issueVouchers(d) {
  if (issuing) return; issuing = true;
  show('vouchers');
  const fail = (msg) => { $('vstatus').textContent = msg; issuing = false; };
  try {
    if (!window.SPStore || !window.Blind || !(window.crypto && crypto.subtle)) return fail('This browser cannot create private vouchers (needs a secure connection, https or localhost).');
    let pend = SPStore.getPending(id);
    if (!pend && d.issued) {
      if (!SPStore.isDone(id)) return fail('These vouchers were already created on another device or browser. Open this page there to find them in the wallet.');
      $('vstatus').textContent = '✓ Your vouchers for this payment are already in your wallet on this device.';
      $('vwallet').classList.remove('hidden'); issuing = false; clearInterval(timerId); return;
    }
    if (!pend) {
      const info = await (await fetch('/api/vouchers/info')).json();
      const items = await Blind.prepare({ n: info.n, e: info.e, epoch: info.epoch, count: d.quantity });
      pend = { epoch: info.epoch, n: info.n, e: info.e, cooldown: info.cooldownDays, items };
      if (!SPStore.setPending(id, pend)) return fail('Browser storage is blocked, so vouchers cannot be kept safely. Allow site storage and reload.');
    }
    const res = await fetch(`/api/vouchers/${id}/issue`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ epoch: pend.epoch, blinded: pend.items.map((i) => i.blinded) }) });
    const out = await res.json();
    if (res.status === 409 && out.retry) { SPStore.clearPending(id); issuing = false; return issueVouchers(d); }
    if (!res.ok) return fail(out.error === 'Vouchers already issued for this order'
      ? 'These vouchers were already created on another device or browser. Open this page there to find them in the wallet.' : (out.error || 'Could not create vouchers'));
    const tokens = [];
    for (let i = 0; i < pend.items.length; i++) {
      const sig = await Blind.finalize({ n: pend.n, e: pend.e, epoch: pend.epoch, secret: pend.items[i].secret, r: pend.items[i].r, blindSig: out.sigs[i] });
      tokens.push({ token: Blind.encodeToken(pend.epoch, pend.items[i].secret, sig), epoch: pend.epoch });
    }
    if (!SPStore.add(tokens)) return fail('Could not save vouchers in this browser.');
    SPStore.clearPending(id); SPStore.markDone(id);
    $('vstatus').textContent = `✓ ${tokens.length} voucher(s) saved in your wallet on this device.`;
    $('vhelp').textContent = `Usable from ${dateOf(pend.epoch + pend.cooldown)} (UTC). The shop cannot link them to this payment. Only this browser holds them, so back them up from the wallet page.`;
    $('vwallet').classList.remove('hidden');
    clearInterval(timerId);
  } catch (e) { fail('Something went wrong creating vouchers: ' + e.message); }
}

async function refresh(first) {
  let r;
  try { r = await fetch('/api/public/' + id); } catch (_) { return; }
  if (r.status === 404) return finish('?', 'Payment request not found.');
  const d = await r.json();
  $('merchant').textContent = d.merchant;
  if (d.status === 'paid') {
    if (d.kind === 'vouchers') { if (!issuing) issueVouchers(d); return; }
    return finish('✓', 'Payment received. Thank you!');
  }
  if (d.status === 'expired') return finish('⏱', 'This request expired. Ask the merchant for a new one.');
  if (d.status === 'cancelled') return finish('✕', 'This request was cancelled.');
  if (first) {
    uri = d.uri;
    $('amount').textContent = d.amount; $('ref').textContent = d.ref;
    $('label').textContent = d.label || '';
    $('qr').innerHTML = d.qrSvg;   // generated by our own server
    $('open').href = d.uri;
    if (d.demo) $('demobox').classList.remove('hidden');
    show('content');
    const tick = () => {
      const s = Math.max(0, Math.round((d.expiresAt - Date.now()) / 1000));
      $('timer').textContent = `Expires in ${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
    };
    tick(); timerId = setInterval(tick, 1000);
  }
}
$('copy').onclick = async () => {
  try { await navigator.clipboard.writeText(uri); $('copy').textContent = 'Copied'; } catch (_) { $('copy').textContent = 'Copy failed'; }
  setTimeout(() => { $('copy').textContent = 'Copy payment link'; }, 1500);
};
$('sim').onclick = async () => {
  $('sim').disabled = true;
  try { await fetch('/api/demo/paid/' + id, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' }); } catch (_) { /* refresh shows the state */ }
  refresh(false);
};
refresh(true);
setInterval(() => { if (!issuing) refresh(false); }, 4000);
